"""
v6.8 -- bounded layer audit: first hidden layer against the pre-logit layer.

The paper's result concerns ONE late representation. This script asks, on the same nine primary
seeds, the same complete input grid, the same metric and the same endpoint recombination, what
the first hidden layer does. It exists to bound the claim, not to open a depth storyline.

Per seed and per layer, at initialisation and convergence:
  label silhouette, L_2, PH-dimension, TwoNN;
and over the endpoint recombination:
  the raw 2x2 for each estimator, both factor orders, the interaction, and the symmetric
  centroid allocation.

Activations are regenerated by forward passes through the existing checkpoints. No training.

Output: RESULTS_v6_8/layer_audit.csv (per seed x layer x estimator)
        RESULTS_v6_8/layer_audit_summary.csv
"""
from __future__ import annotations
import json
import os
import sys
import time
import warnings
from pathlib import Path

os.environ.setdefault("CUDA_VISIBLE_DEVICES", "")
warnings.filterwarnings("ignore")
for _v in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS"):
    os.environ.setdefault(_v, "1")

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))

import numpy as np
import pandas as pd
import torch
from sklearn.metrics import silhouette_score
from sklearn.neighbors import NearestNeighbors

from analysis import geom
from analysis.lsrun import LandscapeRun
from tools.b3_seed_alpha import select
from tools.train_topology import build_task

OUT = REPO / "RESULTS_v6_8"
OUT.mkdir(exist_ok=True)

# activations[-2] is the pre-logit layer the paper measures; activations[0] is the first hidden
LAYERS = {"hidden1": 0, "pre_logit": -2}
ESTS = ("ph_dim", "twonn")


def full_grid_inputs(meta):
    p = meta["p"]
    pairs, y, n_sym, _ = build_task(meta["task"], p, sym_n=5)
    N = len(y)
    X = torch.zeros(N, 2 * n_sym)
    X[torch.arange(N), torch.as_tensor(pairs[:, 0])] = 1.0
    X[torch.arange(N), n_sym + torch.as_tensor(pairs[:, 1])] = 1.0
    return X, np.asarray(y)


def parts(H, y):
    cen = np.zeros_like(H)
    for c in np.unique(y):
        cen[y == c] = H[y == c].mean(0)
    return cen, H - cen


def trace_norm(Z):
    Zc = Z - Z.mean(0)
    return Zc / (np.sqrt((Zc ** 2).sum(1).mean()) + 1e-12)


def leakage(Z, y, q=2):
    nn = NearestNeighbors(n_neighbors=q + 1).fit(Z)
    _, idx = nn.kneighbors(Z)
    lab = np.asarray(y)[idx[:, 1:q + 1]]
    return float(np.mean((lab != np.asarray(y)[:, None]).any(1)))


def measure(Z, y):
    return {"ph_dim": geom.ph_dim(Z)[0], "twonn": geom.twonn(Z),
            "sil": float(silhouette_score(Z, y)), "L2": leakage(Z, y)}


def main():
    inv = pd.read_csv(REPO / "RESULTS" / "_inventory.csv")
    sel = select(inv)
    rows, t0 = [], time.time()
    for i, (_, rec) in enumerate(sel.iterrows()):
        d = REPO / "runs_topo" / rec["dir"]
        try:
            r = LandscapeRun(d)
            meta = json.loads((d / "run_meta.json").read_text())
            X, y = full_grid_inputs(meta)
            acts = {}
            for tag, ckpt in (("init", 0), ("conv", len(r.epochs) - 1)):
                r._load(r.flat(ckpt)); r.model.eval()
                with torch.no_grad():
                    r.model(X, keep_activations=True)
                    acts[tag] = [a.numpy() for a in r.model.activations]
        except Exception as e:
            print(f"  skip {rec['dir'][:48]}: {type(e).__name__} {e}", flush=True)
            continue

        for lname, li in LAYERS.items():
            H0, H1 = acts["init"][li], acts["conv"][li]
            cen0, res0 = parts(H0, y)
            cen1, res1 = parts(H1, y)
            f = {}
            for si, cs in ((0, cen0), (1, cen1)):
                for ti, rs in ((0, res0), (1, res1)):
                    f[(si, ti)] = measure(trace_norm(cs + rs), y)
            for est in ESTS:
                f00, f10 = f[(0, 0)][est], f[(1, 0)][est]
                f01, f11 = f[(0, 1)][est], f[(1, 1)][est]
                diag = f00 - f11
                c1, c2 = f00 - f10, f01 - f11
                phi = 0.5 * (c1 + c2)
                ok = abs(diag) >= 0.05 * max(abs(f00), 1e-12)
                rows.append({
                    "seed": int(rec["seed"]), "dir": rec["dir"], "layer": lname,
                    "estimator": est, "f00": f00, "f10": f10, "f01": f01, "f11": f11,
                    "diag": diag, "centroid_first_raw": c1, "centroid_second_raw": c2,
                    "interaction_raw": f00 - f10 - f01 + f11, "phi_centroid_raw": phi,
                    "symmetric_share": phi / diag if ok else np.nan,
                    "denominator_ok": ok,
                    "sil_init": f[(0, 0)]["sil"], "sil_conv": f[(1, 1)]["sil"],
                    "L2_init": f[(0, 0)]["L2"], "L2_conv": f[(1, 1)]["L2"],
                })
        print(f"  [{i+1}/{len(sel)}] seed {int(rec['seed']):>2} ({time.time()-t0:.0f}s)",
              flush=True)
        pd.DataFrame(rows).to_csv(OUT / "layer_audit.csv", index=False)

    D = pd.DataFrame(rows)
    D.to_csv(OUT / "layer_audit.csv", index=False)

    def rng(v):
        v = np.asarray([x for x in v if np.isfinite(x)], float)
        return (np.nan, np.nan, np.nan) if not len(v) else (np.median(v), v.min(), v.max())

    summ = []
    for (lname, est), g in D.groupby(["layer", "estimator"]):
        rec = {"layer": lname, "estimator": est, "n_seeds": g.seed.nunique(),
               "n_denominator_ok": int(g.denominator_ok.sum())}
        for col in ("sil_init", "sil_conv", "L2_init", "L2_conv", "f00", "f11", "diag",
                    "interaction_raw", "phi_centroid_raw", "symmetric_share"):
            m, lo, hi = rng(g[col])
            rec[f"{col}_med"], rec[f"{col}_min"], rec[f"{col}_max"] = m, lo, hi
        summ.append(rec)
    S = pd.DataFrame(summ)
    S.to_csv(OUT / "layer_audit_summary.csv", index=False)

    print("\n=== layer audit, nine primary seeds, complete input grid ===")
    for _, r in S.iterrows():
        print(f"  {r.layer:>10s} {r.estimator:>7s}  "
              f"sil {r.sil_init_med:+.3f} -> {r.sil_conv_med:+.3f}   "
              f"L2 {r.L2_init_med:.3f} -> {r.L2_conv_med:.3f}   "
              f"{r.f00_med:6.2f} -> {r.f11_med:6.2f}  (diag {r.diag_med:+6.2f})   "
              f"I {r.interaction_raw_med:+6.2f}   "
              f"symmetric {100*r.symmetric_share_med:6.1f}% "
              f"[{100*r.symmetric_share_min:.0f}, {100*r.symmetric_share_max:.0f}]"
              f"  ({r.n_denominator_ok}/{r.n_seeds} pass the denominator rule)")
    print("\nwrote RESULTS_v6_8/layer_audit.csv, layer_audit_summary.csv")


if __name__ == "__main__":
    main()
