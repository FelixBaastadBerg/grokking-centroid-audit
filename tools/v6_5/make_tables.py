"""
v6.5: emit the two tables that previously carried a different input population from the rest of
the paper, as LaTeX fragments generated directly from the result files.

  paper/tables_v6_5/intervention_battery.tex   the alpha sweep battery (was Table 3)
  paper/tables_v6_5/phase_shares.tex           the checkpoint-resolved shares (was Table 9)

Both are now computed on the primary population: the complete Z_23 x Z_23 input grid, 529
points, exactly 23 per class, nine seeds. Writing them as generated fragments means the numbers
cannot drift from the data the way hand-typed table bodies did.
"""
from __future__ import annotations
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))

import numpy as np
import pandas as pd

R4 = REPO / "RESULTS_v6_4"
R5 = REPO / "RESULTS_v6_5"
OUT = REPO / "paper" / "tables_v6_5"
OUT.mkdir(parents=True, exist_ok=True)

HEAD = ("% GENERATED by tools/v6_5/make_tables.py -- do not hand-edit.\n"
        "% Source: {src}\n")


def battery():
    S = pd.read_csv(R5 / "intervention_battery_summary.csv")
    order = ["H1_total", "ph_dim", "eff_rank", "mle_k10", "pca_pr", "spec_entropy",
             "corr_dim", "twonn", "H1_max"]
    S = S.set_index("estimator").loc[order].reset_index()
    L = [HEAD.format(src="RESULTS_v6_5/intervention_battery_summary.csv"),
         r"\begin{tabular}{lrrrl}", r"\toprule",
         r"statistic & $\alpha{=}0$ & $\alpha{=}8$ & fold & seed range \\", r"\midrule"]
    for _, r in S.iterrows():
        bold = r.estimator in ("ph_dim", "twonn")
        nm = r["name"]
        fmt = "%.2f" if abs(r.median_at_0) < 1 else "%.1f"
        a0, a8 = fmt % r.median_at_0, fmt % r.median_at_8
        fold = f"{r.fold_ratio_of_medians_0_8:.2f}\\times"
        # an en-dash range must sit outside math mode, or "--" renders as two minus signs
        rng = f"${r.fold_seed_min_0_8:.2f}$--${r.fold_seed_max_0_8:.2f}$"
        if bold:
            nm, a0, a8, fold = (f"\\textbf{{{nm}}}", f"$\\mathbf{{{a0}}}$",
                                f"$\\mathbf{{{a8}}}$", f"$\\mathbf{{{fold}}}$")
        else:
            a0, a8, fold = f"${a0}$", f"${a8}$", f"${fold}$"
        L.append(f"{nm} & {a0} & {a8} & {fold} & {rng} \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    (OUT / "intervention_battery.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote intervention_battery.tex ({len(S)} rows)")


PHASE_LABEL = {
    "init->pre-grok": r"$0 \to 1$ (init $\to$ pre-grok)",
    "pre-grok->t_grok": r"$1 \to 2$ (pre-grok $\to t_{\text{grok}}$)",
    "t_grok->post-mid": r"$2 \to 3$ ($t_{\text{grok}} \to$ post-mid)",
    "post-mid->conv": r"$3 \to 4$ (post-mid $\to$ conv.)",
    "init->t_grok": r"$0 \to 2$ (init $\to t_{\text{grok}}$)",
    "t_grok->conv": r"$2 \to 4$ ($t_{\text{grok}} \to$ conv.)",
    "init->conv (endpoint)": r"$0 \to 4$ (full)",
}
ORDER = ["init->pre-grok", "pre-grok->t_grok", "t_grok->post-mid", "post-mid->conv",
         None, "init->t_grok", "t_grok->conv", None, "init->conv (endpoint)"]


MIN_DENOM = 0.05   # the denominator rule already used elsewhere in the paper


def phases():
    """
    Per-seed rather than per-median. A share is a ratio, so it is uninformative whenever that
    seed's own change over the interval is a negligible fraction of its own full-trajectory
    change -- even if the MEDIAN interval change clears the threshold. Applying the same 5%
    rule seed by seed is what keeps a single near-zero denominator from producing a seed range
    like [-24083, 394]. Raw contributions are always shown, since they need no denominator.
    """
    S = pd.read_csv(R4 / "fullgrid_shapley.csv")
    S = S[S.pipeline == "raw"]
    L = [HEAD.format(src="RESULTS_v6_4/fullgrid_shapley.csv"),
         # six columns of mixed widths overflow \textwidth at the default column separation
         r"\setlength{\tabcolsep}{4pt}",
         r"\begin{tabular}{lrrlrl}", r"\toprule",
         r"& & \multicolumn{2}{c}{PH-dimension} & \multicolumn{2}{c}{TwoNN} \\",
         r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}",
         r"interval & change & share & seed range & share & seed range \\",
         r"\midrule"]
    for key in ORDER:
        if key is None:
            L.append(r"\midrule")
            continue
        p = S[(S.estimator == "ph_dim") & (S.phase == key)]
        t = S[(S.estimator == "twonn") & (S.phase == key)]
        carried = f"{100*p.rel_change.median():.0f}\\%"

        def cell(q):
            ok = q[q.rel_change >= MIN_DENOM]
            s = f"{100*q.between_share.median():.0f}\\%"
            if len(ok) < len(q):
                return f"\\emph{{{s}}}", f"\\emph{{{len(q)-len(ok)} seed(s) below denom.}}"
            return s, (f"[{100*ok.between_share.min():.0f}, "
                       f"{100*ok.between_share.max():.0f}]")

        ps, pg = cell(p)
        ts, tg = cell(t)
        L.append(f"{PHASE_LABEL[key]} & {carried} & {ps} & {pg} & {ts} & {tg} \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    (OUT / "phase_shares.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote phase_shares.tex")

    fp = S[(S.estimator == "ph_dim") & (S.phase == "init->conv (endpoint)")]
    ft = S[(S.estimator == "twonn") & (S.phase == "init->conv (endpoint)")]
    print("\n  full-interval check (must match the main text):")
    print(f"    PH-dimension {100*fp.between_share.median():.0f}%"
          f"   TwoNN {100*ft.between_share.median():.0f}%")


if __name__ == "__main__":
    battery()
    phases()
